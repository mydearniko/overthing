// EmbeddedRelays parses the hardcoded relay URLs and returns valid entries.
// Invalid or unparseable entries are silently skipped.
func EmbeddedRelays() []Relay {
	relays := make([]Relay, 0, len(embeddedRelayURLs))
	for _, rawURL := range embeddedRelayURLs {
		r, err := ParseURL(rawURL)
		if err != nil {
			continue
		}
		relays = append(relays, *r)
	}
	return relays
}
